const AUTOMATION_USER = {
  id: "blog20-automations",
  sub: "blog20-automations",
  email: "blog20-automations@system.local",
  role: "super_admin",
  permissions: { blog_2_0: { add: true, delete: true, edit: true, view: true } },
};

const STALE_MIN = Number(process.env.BLOG_20_AUTOMATIONS_STALE_MIN || 50);

function scheduleSettingsFromBlog20(settings) {
  let runDays = settings.automation_run_days || [1];
  if (settings.automation_frequency === "daily") {
    runDays = [0, 1, 2, 3, 4, 5, 6];
  }
  return {
    enabled: Boolean(settings.automation_enabled),
    timezone: settings.timezone || "Asia/Kolkata",
    run_time: settings.automation_run_time || "12:00",
    run_days: runDays,
    last_run_at: settings.automation_last_run_at || null,
    window_start: null,
    window_end: null,
  };
}

export function shouldRunBlog20Now(settings, now = new Date()) {
  const schedule = scheduleSettingsFromBlog20(settings);
  const check = checkScheduleDue(schedule, now);
  if (!check.ok) return check;

  if (settings.automation_frequency === "monthly") {
    const local = getLocalParts(now, schedule.timezone);
    if (local.day !== 1) {
      return { ok: false, reason: "monthly_not_first_day" };
    }
  }

  return { ok: true, reason: "due" };
}

export function describeBlog20ScheduleStatus(settings, now = new Date()) {
  const schedule = scheduleSettingsFromBlog20(settings);
  return describeScheduleStatus(schedule, now);
}

function buildAutomationPrompt(topic, settings) {
  const niche = settings.automation_auto_niche || "construction CRM, contractors, project management";
  return [
    `Write a complete Bright CRM blog post for the client's MailerLite website.`,
    `Topic: "${topic.topic}"`,
    topic.notes ? `Notes: ${topic.notes}` : "",
    `Audience & niche: ${niche}`,
    "Match existing posts on the client /blog (800–1200 words, H2 sections, practical construction CRM angle).",
    "Author: Bright CRM Team.",
    "IMPORTANT: Do not ask questions. Research the angle yourself, then call create_bright_crm_blog_draft once with full HTML.",
    "Status pending — team must approve via email before MailerLite push (unless auto-push is on in settings).",
    "Reply briefly after saving with draft id and title.",
  ]
    .filter(Boolean)
    .join("\n");
}

function parseDraftFromRun(runResult) {
  const posts = runResult?.posts || [];
  if (posts[0]?.id) {
    return {
      draftId: Number(posts[0].id),
      title: posts[0].title || null,
      approvalId: posts[0].approval?.approvalId || posts[0].approvalId || null,
    };
  }
  const text = String(runResult?.output || "");
  const idMatch = text.match(/\b(?:draft|id)\D{0,6}#?(\d{1,8})\b/i);
  return {
    draftId: idMatch ? Number(idMatch[1]) : null,
    title: null,
    approvalId: null,
  };
}

async function ensureTopicsForRun(settings) {
  const limit = Math.min(Math.max(Number(settings.automation_posts_per_run || 1), 1), 5);
  if (settings.automation_topic_source !== "auto_research") {
    return { autoGenerated: [] };
  }

  const queued = await topicsModel.countQueuedTopics();
  const need = Math.max(0, limit - queued);
  if (!need) return { autoGenerated: [] };

  const avoidTopics = await topicsModel.listRecentTopicTitles(50);
  const niche =
    settings.automation_auto_niche ||
    "construction CRM, general contractors, project managers, bids and pipeline, jobsite efficiency";

  const picks = await discoverTrendingTopics({
    count: need,
    niche,
    avoidTopics,
  });

  const created = [];
  for (const pick of picks) {
    const topic = await topicsModel.createTopic({
      topic: pick.topic,
      notes: pick.notes
        ? `[Auto research]\n${pick.notes}`
        : "[Auto research] Trending angle for Bright CRM blog.",
      priority: 10,
      created_by: "auto-research",
    });
    created.push(topic);
  }

  if (created.length) {
    console.log(
      `[blog20-automations] auto-research queued ${created.length}: ${created.map((t) => t.topic).join(" | ")}`,
    );
  }
  return { autoGenerated: created };
}

async function processTopic(topic, settings) {
  await topicsModel.markTopicProcessing(topic.id);

  const prompt = buildAutomationPrompt(topic, settings);
  const thread = await blogAgentModel.createThread({
    userId: AUTOMATION_USER.id,
    userEmail: AUTOMATION_USER.email,
    title: `Automation: ${topic.topic}`.slice(0, 120),
    agentType: "blog_2_0",
  });

  await blogAgentModel.addMessage({
    threadId: thread.id,
    role: "user",
    content: prompt,
  });

  let runResult = await runBlog20Agent({
    user: AUTOMATION_USER,
    threadId: thread.id,
    message: prompt,
    writeNowMode: true,
  });

  let parsed = parseDraftFromRun(runResult);
  if (!parsed.draftId) {
    const retry =
      "Call create_bright_crm_blog_draft NOW with the full blog HTML. Save the draft — no questions.";
    await blogAgentModel.addMessage({ threadId: thread.id, role: "user", content: retry });
    runResult = await runBlog20Agent({
      user: AUTOMATION_USER,
      threadId: thread.id,
      message: retry,
      writeNowMode: true,
    });
    parsed = parseDraftFromRun(runResult);
  }

  await blogAgentModel.addMessage({
    threadId: thread.id,
    role: "assistant",
    content: String(runResult.output || "Done."),
    toolOutput: {
      durationMs: runResult.durationMs || null,
      source: "blog20-automations",
      posts: runResult.posts || [],
    },
  });

  if (!parsed.draftId) {
    throw new Error("Agent did not save a draft (create_bright_crm_blog_draft missing).");
  }

  const title =
    parsed.title ||
    runResult.posts?.[0]?.title ||
    topic.topic;

  await topicsModel.markTopicDone(topic.id, {
    draftId: parsed.draftId,
    title,
    approvalId: parsed.approvalId,
  });

  return {
    topicId: topic.id,
    draftId: parsed.draftId,
    title,
    approvalId: parsed.approvalId,
  };
}

async function processTopicBatch(settings, dueTopics) {
  const staggerSec = Math.min(
    Math.max(Number(settings.automation_posts_stagger_seconds ?? 120), 0),
    900,
  );
  const results = [];
  for (let i = 0; i < dueTopics.length; i += 1) {
    const topic = dueTopics[i];
    if (i > 0 && staggerSec > 0) {
      await sleep(staggerSec * 1000);
    }
    const started = Date.now();
    try {
      const out = await processTopic(topic, settings);
      results.push({ ok: true, ...out, durationMs: Date.now() - started });
    } catch (err) {
      await topicsModel.markTopicFailed(topic.id, err.message);
      results.push({
        ok: false,
        topicId: topic.id,
        error: err.message,
        durationMs: Date.now() - started,
      });
    }
  }
  return results;
}

export async function runBlog20AutomationTick() {
  await topicsModel.releaseStaleProcessingTopics(STALE_MIN);

  const settings = await settingsModel.getSettings();
  const schedule = shouldRunBlog20Now(settings);
  if (!schedule.ok) {
    return { ran: false, reason: schedule.reason || "not_due" };
  }

  let autoMeta = { autoGenerated: [] };
  try {
    autoMeta = await ensureTopicsForRun(settings);
  } catch (err) {
    console.error("[blog20-automations] auto-research failed:", err.message);
    return {
      ran: true,
      processed: 0,
      results: [],
      autoResearchError: err.message,
    };
  }

  const limit = Math.min(Math.max(Number(settings.automation_posts_per_run || 1), 1), 5);
  const dueTopics = await topicsModel.getDueTopics(limit);
  if (!dueTopics.length) {
    return {
      ran: true,
      processed: 0,
      results: [],
      autoGeneratedTopics: autoMeta.autoGenerated,
    };
  }

  const results = await processTopicBatch(settings, dueTopics);
  await settingsModel.markAutomationLastRun(new Date());

  return {
    ran: true,
    processed: dueTopics.length,
    results,
    autoGeneratedTopics: autoMeta.autoGenerated,
  };
}

export async function runBlog20AutomationNow(options = {}) {
  await topicsModel.releaseStaleProcessingTopics(STALE_MIN);
  const settings = await settingsModel.getSettings();

  if (options.bootstrapResearch) {
    await ensureTopicsForRun({
      ...settings,
      automation_topic_source: "auto_research",
    });
  } else if (settings.automation_topic_source === "auto_research") {
    await ensureTopicsForRun(settings);
  }

  const limit = Math.min(
    Math.max(Number(options.limit || settings.automation_posts_per_run || 1), 1),
    5,
  );
  const dueTopics = await topicsModel.getDueTopics(limit);
  if (!dueTopics.length) {
    return {
      ran: true,
      processed: 0,
      results: [],
      message: "No topics in queue. Add a topic or enable Auto research.",
    };
  }

  const results = await processTopicBatch(settings, dueTopics);
  await settingsModel.markAutomationLastRun(new Date());
  return { ran: true, processed: dueTopics.length, results };
}
